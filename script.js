const WEBHOOK_URL = "https://cstep-n8n.york.cuny.edu/webhook/9c6c076f-7f8e-4a4b-889c-fc758b719cee";
// n8n webhook that returns today's Eventbrite events and agenda sessions.
const EVENTS_TODAY_URL = "https://cstep-n8n.york.cuny.edu/webhook/2a907495-f16f-451f-a374-345979e508b0";

// Timezone used when comparing event dates.
const LOCAL_TIME_ZONE = "America/New_York";

// How long (in milliseconds) to pause scanning after each scan.
// 3000 = 3 seconds. This prevents the same QR from being sent twice.
const SCAN_COOLDOWN_MS = 3000;

// localStorage key for remembering this phone's last event + activity.
const LAST_CHOICE_KEY = "cstepScanner.lastChoice";


