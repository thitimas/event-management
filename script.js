$("activitySelect").addEventListener("change", onActivitySwitch);
$("copyLinkBtn").addEventListener("click", copyActivityLink);

loadEventsToday().then(restoreInitialChoice);


// ---------------------------------------------------------------------------
// STATUS MESSAGE
// Shows a colored message bar below the scanner.
// type can be: "success" (green), "warning" (yellow), "error" (red), "info" (blue)
// ---------------------------------------------------------------------------
function showStatus(message, type) {
  const area = $("statusArea");
  const msg  = $("statusMessage");
  msg.textContent = message;
  msg.className   = `status-message ${type}`;
  area.classList.remove("hidden");
}

function hideStatus() {
  $("statusArea").classList.add("hidden");
}

function showSetupError(message) {
  $("setupError").textContent = message;
  $("setupError").classList.remove("hidden");
}

function hideSetupError() {
  $("setupError").classList.add("hidden");
  $("setupError").textContent = "";
}


// ---------------------------------------------------------------------------
// EVENTBRITE EVENTS
// Reads the static JSON file generated by GitHub Actions. The browser never
// receives the Eventbrite API token.
// ---------------------------------------------------------------------------
function getLocalDateString(date = new Date()) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: LOCAL_TIME_ZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);

  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

function setEventSelectOptions(events) {
  const select = $("eventSelect");
  select.textContent = "";

  const placeholder = document.createElement("option");
  placeholder.value = "";
  placeholder.textContent = "— Select today's event —";
  select.appendChild(placeholder);

  events.forEach((event) => {
    const option = document.createElement("option");
    option.value = event.id;
    option.textContent = event.starts_at
      ? `${formatEventTime(event.starts_at)} — ${event.name}`
      : event.name;
    select.appendChild(option);
  });

  select.disabled = events.length === 0;

  // Reset the session dropdown whenever the event list is rebuilt.
  setSessionOptions(null);
}

// Populate the session dropdown from the selected event's agenda.
// agenda === null  -> no event chosen yet
// agenda === []    -> event chosen but it has no agenda sessions
function setSessionOptions(agenda) {
  const select = $("sessionSelect");
  const status = $("sessionStatus");
  select.textContent = "";
  status.textContent = "";

  if (agenda === null) {
    select.appendChild(makeOption("", "— Select an event first —"));
    select.disabled = true;
    return;
  }

  if (agenda.length === 0) {
    select.appendChild(makeOption("", "— No agenda sessions for this event —"));
    select.disabled = true;
    status.textContent = "This event has no agenda sessions in Eventbrite.";
    return;
  }

  select.appendChild(makeOption("", "— Select a session —"));
  agenda.forEach((session) => {
    select.appendChild(makeOption(session.title, sessionLabel(session)));
  });
  select.disabled = false;
}

function sessionLabel(session) {
  return session.start_time
    ? `${formatAgendaTime(session.start_time)} — ${session.title}`
    : session.title;
}

function makeOption(value, text) {
  const option = document.createElement("option");
  option.value = value;
  option.textContent = text;
  return option;
}

// Called when the coordinator picks a different event.
function onEventChange() {
  hideSetupError();
  const event = todayEvents.find((item) => item.id === $("eventSelect").value);
  setSessionOptions(event ? event.agenda : null);
  if (event) $("sessionSelect").value = pickCurrentSession(event.agenda);
}

// "HH:MM" -> minutes since midnight, or null if the time is missing/invalid.
function parseAgendaMinutes(hhmm) {
  const match = /^(\d{1,2}):(\d{2})$/.exec(hhmm || "");
  if (!match) return null;
  return parseInt(match[1], 10) * 60 + parseInt(match[2], 10);
}

// Minutes since midnight right now, in LOCAL_TIME_ZONE.
function getLocalMinutesNow(date = new Date()) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: LOCAL_TIME_ZONE,
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).formatToParts(date);

  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return (parseInt(values.hour, 10) % 24) * 60 + parseInt(values.minute, 10);
}

// Pick the session that most recently started; if none have started yet,
// the earliest one. Returns "" when no session has a usable start time.
function pickCurrentSession(agenda) {
  const now = getLocalMinutesNow();
  let latestStarted = null;
  let earliest = null;

  agenda.forEach((session) => {
    const minutes = parseAgendaMinutes(session.start_time);
    if (minutes === null) return;
    if (!earliest || minutes < earliest.minutes) earliest = { session, minutes };
    if (minutes <= now && (!latestStarted || minutes >= latestStarted.minutes)) {
      latestStarted = { session, minutes };
    }
  });

  const pick = latestStarted || earliest;
  return pick ? pick.session.title : "";
}

// Agenda times come from Eventbrite as a 24-hour "HH:MM" clock string.
function formatAgendaTime(hhmm) {
  const match = /^(\d{1,2}):(\d{2})$/.exec(hhmm || "");
  if (!match) return hhmm || "";
  let hour = parseInt(match[1], 10);
  const minutes = match[2];
  const period = hour >= 12 ? "PM" : "AM";
  hour = hour % 12 || 12;
  return `${hour}:${minutes} ${period}`;
}

function setEventStatus(message, type) {
  const status = $("eventListStatus");
  status.textContent = message;
  status.className = `form-help ${type || ""}`.trim();
}

function formatEventTime(isoString) {
  try {
    return new Intl.DateTimeFormat("en-US", {
      timeZone: LOCAL_TIME_ZONE,
      hour: "numeric",
      minute: "2-digit",
    }).format(new Date(isoString));
  } catch (_) {
    return "";
  }
}

async function loadEventsToday() {
  const select = $("eventSelect");
  const refreshButton = document.querySelector(".btn-small");
  const today = getLocalDateString();

  todayEvents = [];
  select.disabled = true;
  select.textContent = "";
  const loadingOption = document.createElement("option");
  loadingOption.value = "";
  loadingOption.textContent = "Loading today's events...";
  select.appendChild(loadingOption);
  setEventStatus("Loading today's Eventbrite events...", "");
  hideSetupError();

  if (refreshButton) refreshButton.disabled = true;

  try {
    const response = await fetch(`${EVENTS_TODAY_URL}?v=${Date.now()}`, {
      cache: "no-store",
    });

    if (!response.ok) {
      throw new Error(`Could not load ${EVENTS_TODAY_URL}.`);
    }

    const data = await response.json();
    const events = Array.isArray(data.events) ? data.events : [];

    if (data.date !== today) {
      throw new Error(`The event list is for ${data.date || "an unknown date"}, not ${today}.`);
    }

    todayEvents = events
      .filter((event) => event && event.id && event.name)
      .map((event) => ({
        id: String(event.id),
        name: String(event.name),
        starts_at: event.starts_at ? String(event.starts_at) : "",
        agenda: (Array.isArray(event.agenda) ? event.agenda : [])
          .filter((session) => session && session.title)
          .map((session) => ({
            title: String(session.title),
            start_time: session.start_time ? String(session.start_time) : "",
          })),
      }))
      .filter((event) => event.agenda.length > 0);

    if (todayEvents.length === 0) {
      throw new Error("No events with agenda sessions are available for today.");
    }

    setEventSelectOptions(todayEvents);
    setEventStatus(
      `Loaded ${todayEvents.length} event${todayEvents.length === 1 ? "" : "s"} for ${today}.`,
      "success"
    );
  } catch (err) {
    todayEvents = [];
    setEventSelectOptions([]);
    setEventStatus(err.message || "Could not load today's events.", "error");
  } finally {
    if (refreshButton) refreshButton.disabled = false;
  }
}


// ---------------------------------------------------------------------------
// LAST SCAN DETAILS
// Displays a summary of the most recent scan at the bottom of the page.
// ---------------------------------------------------------------------------
function showLastScan({ studentName, sessionTitle, timestamp }) {
  const details = $("lastScanDetails");
  details.textContent = "";

  addDetailRow(details, "Student:", studentName || "—");
  addDetailRow(details, "Session:", sessionTitle);
  addDetailRow(details, "Time:", new Date(timestamp).toLocaleTimeString());

  $("lastScan").classList.remove("hidden");
}

function addDetailRow(parent, label, value) {
  const row = document.createElement("div");
  row.className = "detail-row";

  const labelEl = document.createElement("span");
  labelEl.className = "detail-label";
  labelEl.textContent = label;

  const valueEl = document.createElement("span");
  valueEl.textContent = value || "—";

  row.append(labelEl, valueEl);
  parent.appendChild(row);
}


// ---------------------------------------------------------------------------
// TOKEN EXTRACTION
// QR codes may contain a full URL or just a plain token string.
// ---------------------------------------------------------------------------
function extractToken(scannedText) {
  scannedText = scannedText.trim();
  try {
    const url   = new URL(scannedText);
    const token = url.searchParams.get("token");
    if (token) return token;
  } catch (_) {
    // Not a valid URL — treat the whole string as the token
  }
  return scannedText;
}


// ---------------------------------------------------------------------------
// SETUP — confirm event details before scanning begins
// ---------------------------------------------------------------------------
function confirmSetup() {
  const eventSelect   = $("eventSelect");
  const sessionSelect = $("sessionSelect");
  const selectedEvent = todayEvents.find((event) => event.id === eventSelect.value);

  hideSetupError();

  if (todayEvents.length === 0 || eventSelect.disabled) {
    showSetupError("Please load today's Eventbrite events before scanning.");
    return;
  }

  if (!selectedEvent) {
    showSetupError("Please select today's Eventbrite event.");
    eventSelect.focus();
    return;
  }

  const session = (selectedEvent.agenda || []).find((item) => item.title === sessionSelect.value);

  if (!session) {
    showSetupError("Please select a session from the agenda.");
    sessionSelect.focus();
    return;
  }

  activateSession(selectedEvent, session);
}

// Store the chosen event + activity, update the scanner panel, and show it.
// Used by the setup form, activity links, and the remembered last choice.
function activateSession(event, session) {
  // Store for use in every scan
  sessionEventId     = event.id;
  sessionEventName   = event.name;
  sessionAgendaTitle = session.title;

  // Keep the setup form in sync so "Change Event / Session" starts from here
  $("eventSelect").value = event.id;
  setSessionOptions(event.agenda);

  // Fill the on-scanner activity switcher from this event's agenda
  const activitySelect = $("activitySelect");
  activitySelect.textContent = "";
  event.agenda.forEach((item) => {
    activitySelect.appendChild(makeOption(item.title, sessionLabel(item)));
  });

  $("summaryEvent").textContent = event.name;
  updateActivityDisplay();

  // Switch panels
  $("setupPanel").classList.add("hidden");
  $("scannerPanel").classList.remove("hidden");
}

// Refresh everything that shows the current activity, and remember it.
function updateActivityDisplay() {
  $("currentActivity").textContent = sessionAgendaTitle;
  $("summarySession").textContent  = sessionAgendaTitle;
  $("activitySelect").value        = sessionAgendaTitle;
  $("sessionSelect").value         = sessionAgendaTitle;

  // Any previously shown link was for the old activity
  $("copyLinkStatus").textContent = "";
  $("activityLinkField").classList.add("hidden");

  // Keep the address bar matching the current activity, so a reload
  // reopens this activity instead of an older link's activity
  try {
    history.replaceState(null, "", buildActivityLink());
  } catch (_) {}

  saveLastChoice();
}


// ---------------------------------------------------------------------------
// ACTIVITY SWITCH — change activity from the scanner panel
// The camera keeps running; the next scan uses the new activity.
// ---------------------------------------------------------------------------
function onActivitySwitch() {
  const event   = todayEvents.find((item) => item.id === sessionEventId);
  const session = event && event.agenda.find((item) => item.title === $("activitySelect").value);

  if (!session) {
    $("activitySelect").value = sessionAgendaTitle;
    return;
  }

  sessionAgendaTitle = session.title;
  updateActivityDisplay();

  // The last scan belonged to the previous activity — hide it to avoid confusion
  $("lastScan").classList.add("hidden");
}


// ---------------------------------------------------------------------------
// ACTIVITY LINKS + REMEMBERED CHOICE
// Links look like ?event=<eventId>&session=<session title>. Nothing secret
// goes in the URL. URL params take precedence over the remembered choice.
// ---------------------------------------------------------------------------
function buildActivityLink() {
  const url = new URL(window.location.href);
  url.search = "";
  url.hash   = "";
  url.searchParams.set("event", sessionEventId);
  url.searchParams.set("session", sessionAgendaTitle);
  return url.toString();
}

function findEventSession(eventId, sessionTitle) {
  const event   = todayEvents.find((item) => item.id === eventId);
  const session = event && event.agenda.find((item) => item.title === sessionTitle);
  return { event, session };
}

function saveLastChoice() {
  try {
    localStorage.setItem(LAST_CHOICE_KEY, JSON.stringify({
      date:         getLocalDateString(),
      eventId:      sessionEventId,
      sessionTitle: sessionAgendaTitle,
    }));
  } catch (_) {
    // Storage unavailable (e.g. private mode) — remembering is optional
  }
}

function loadLastChoice() {
  try {
    const saved = JSON.parse(localStorage.getItem(LAST_CHOICE_KEY) || "null");
    return saved && typeof saved === "object" ? saved : null;
  } catch (_) {
    return null;
  }
}

// Runs once, after the first events load.
function restoreInitialChoice() {
  const params      = new URLSearchParams(window.location.search);
  const linkEventId = params.get("event");
  const linkSession = params.get("session");

  if (linkEventId || linkSession) {
    const { event, session } = findEventSession(linkEventId, linkSession);
    if (event && session) {
      activateSession(event, session);
      return;
    }

    if (todayEvents.length === 0) {
      showSetupError("Could not open the activity link because today's events did not load. Tap Refresh, then choose the event and session below.");
    } else if (event) {
      $("eventSelect").value = event.id;
      onEventChange();
      showSetupError(`The activity link's session "${linkSession || ""}" was not found for this event. Please choose a session below.`);
    } else {
      showSetupError("The activity link does not match any of today's events. Please choose the event and session below.");
    }
    return;
  }

  const saved = loadLastChoice();
  if (saved && saved.date === getLocalDateString()) {
    const { event, session } = findEventSession(String(saved.eventId || ""), String(saved.sessionTitle || ""));
    if (event && session) activateSession(event, session);
  }
}

// Copy the activity link; if the clipboard is blocked, show the link in a
// selectable field instead.
async function copyActivityLink() {
  const link   = buildActivityLink();
  const status = $("copyLinkStatus");
  const field  = $("activityLinkField");

  try {
    if (!navigator.clipboard || !navigator.clipboard.writeText) {
      throw new Error("Clipboard not available");
    }
    await navigator.clipboard.writeText(link);
    field.classList.add("hidden");
    status.textContent = "Link copied. Opening it goes straight to this activity.";
    status.className   = "form-help success";
  } catch (_) {
    field.value = link;
    field.classList.remove("hidden");
    field.focus();
    field.select();
    status.textContent = "Could not copy automatically. Select and copy this link:";
    status.className   = "form-help";
  }
}

// Allow admin to go back and change details (stops scanner first)
function resetSetup() {
  stopScanner();
  $("scannerPanel").classList.add("hidden");
  $("setupPanel").classList.remove("hidden");
  hideStatus();
  $("lastScan").classList.add("hidden");
}


// ---------------------------------------------------------------------------
// SCANNER — START
// Initialises the html5-qrcode library and opens the camera.
// ---------------------------------------------------------------------------
async function startScanner() {
  hideStatus();
  $("scannerWrapper").classList.remove("hidden");
  $("startBtn").disabled = true;
  $("stopBtn").disabled  = false;

  // Create the scanner instance the first time
  if (!html5QrCode) {
    html5QrCode = new Html5Qrcode("qr-reader");
  }

  // Scanner settings
  const config = {
    fps: 10,                          // frames per second to check for QR codes
    qrbox: { width: 250, height: 250 }, // the green scanning box size
    aspectRatio: 1.0,
    rememberLastUsedCamera: true,
  };

  // Phones: prefer the rear ("environment") camera. Desktops and Macs have no
  // rear camera, so that constraint fails — fall back to any available camera.
  try {
    await html5QrCode.start({ facingMode: "environment" }, config, onScanSuccess, onScanFailure);
  } catch (envErr) {
    try {
      const cameras = await Html5Qrcode.getCameras();
      if (!cameras || cameras.length === 0) throw envErr;
      const rear = cameras.find((cam) => /back|rear|environment/i.test(cam.label || ""));
      const cameraId = (rear || cameras[0]).id;
      await html5QrCode.start(cameraId, config, onScanSuccess, onScanFailure);
    } catch (err) {
      showStatus("Camera error: " + (err && err.message ? err.message : err), "error");
      resetScannerUI();
    }
  }
}


// ---------------------------------------------------------------------------
// SCANNER — STOP
// Stops the camera and resets the UI.
// ---------------------------------------------------------------------------
function stopScanner() {
  if (html5QrCode && html5QrCode.isScanning) {
    html5QrCode
      .stop()
      .then(() => resetScannerUI())
      .catch((err) => {
        console.warn("Stop error:", err);
        resetScannerUI();
      });
  } else {
    resetScannerUI();
  }
}

function resetScannerUI() {
  $("scannerWrapper").classList.add("hidden");
  $("startBtn").disabled = false;
  $("stopBtn").disabled  = true;
  if (cooldownTimer) clearTimeout(cooldownTimer);
  isCoolingDown = false;
}


// ---------------------------------------------------------------------------
// ON SCAN SUCCESS
// Called automatically by html5-qrcode when a QR code is detected.
// ---------------------------------------------------------------------------
function onScanSuccess(decodedText) {
  // Ignore scans during the cooldown window (prevents duplicate submissions)
  if (isCoolingDown) return;

  // Immediately pause the scanner so the same code isn't sent twice.
  isCoolingDown = true;
  if (html5QrCode) {
    try { html5QrCode.pause(false); } catch (_) {}
  }

  const token     = extractToken(decodedText);
  const timestamp = new Date().toISOString();

  showStatus("Sending check-in data...", "info");

  const payload = {
    qr_token:     token,
    event_id:     sessionEventId,
    event_name:   sessionEventName,
    event_date:   getLocalDateString(),
    agenda_title: sessionAgendaTitle,
  };

  sendCheckin(payload, timestamp);
}

// Called every frame when no QR code is visible — this is normal behaviour.
// We suppress the most common noisy message to keep the console clean.
function onScanFailure(error) {
  if (!error.includes("No MultiFormat Readers")) {
    console.debug("QR scan frame:", error);
  }
}


// ---------------------------------------------------------------------------
// SEND TO N8N WEBHOOK (or simulate if test mode is on)
// ---------------------------------------------------------------------------
async function sendCheckin(payload, timestamp) {
  try {
    let data;

    const response = await fetch(WEBHOOK_URL, {
      method:  "POST",
      headers: { "Content-Type": "application/json" },
      body:    JSON.stringify(payload),
    });

      // Try to parse the JSON response from n8n
      try {
        data = await response.json();
      } catch (_) {
        // n8n returned something that isn't valid JSON
        data = { status: "error", message: "Unexpected response from server." };
      }

    if (!response.ok && data.status !== "duplicate") {
      data.status = "error";
      data.message = data.message || "Server returned an error.";
    }

    handleWebhookResponse(data, payload, timestamp);
  } catch (networkErr) {
    showStatus("Network error: Could not reach the server. Check your connection.", "error");
    resumeAfterCooldown();
  }
}


// ---------------------------------------------------------------------------
// HANDLE N8N RESPONSE
// n8n returns a JSON object with a "status" field.
// ---------------------------------------------------------------------------
function handleWebhookResponse(data, payload, timestamp) {
  const studentName = data.student_name || "";

  if (data.status === "success") {
    showStatus(
      `Checked in${studentName ? ": " + studentName : ""}`,
      "success"
    );
    showLastScan({
      studentName,
      sessionTitle: payload.agenda_title,
      timestamp,
    });
  } else if (data.status === "duplicate") {
    showStatus(
      `Already recorded${studentName ? ": " + studentName : ""}`,
      "warning"
    );
    showLastScan({
      studentName,
      sessionTitle: payload.agenda_title,
      timestamp,
    });
  } else {
    showStatus(`Error: ${data.message || "Unknown error. Please try again."}`, "error");
  }

  // Resume scanning after the cooldown period
  resumeAfterCooldown();
}


// ---------------------------------------------------------------------------
// COOLDOWN RESUME
// Waits SCAN_COOLDOWN_MS milliseconds, then re-activates the scanner.
// ---------------------------------------------------------------------------
function resumeAfterCooldown() {
  cooldownTimer = setTimeout(() => {
    isCoolingDown = false;
    if (html5QrCode) {
      try { html5QrCode.resume(); } catch (_) {}
    }
  }, SCAN_COOLDOWN_MS);
}
